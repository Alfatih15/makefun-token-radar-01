// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token that is not a wrapped, staked or
// bridged product of a token that already trades, not an exchange and not a versioned pool of another
// protocol. That is the watchlist's own rule, applied to the whole snapshot instead of only above its
// $50M floor: the watchlist's 40 slugs are the floor, and the 158 pre-token protocols below the floor
// that pass the same rule are the early rows the radar exists to find. Protocols that fail the rule
// are not hidden: the dashboard's Set aside tab names each one with its reason, and the Live token tab
// carries the protocols whose token already trades, with the market's own market cap, never a model.
//
// Implied value follows only from the snapshot's own figures, through one function of four inputs:
//
//   baseMultiple = median(mcap_usd / tvl_usd) over the snapshot's live-token protocols with a market
//                  cap: what the market itself pays per dollar of TVL, read from the snapshot (~0.20)
//   base         = tvl_usd x baseMultiple
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//                  age is the time since DefiLlama began tracking the protocol: how long it has run
//                  with no token on record, which is the whole of the launch story
//   breadth      = 1 + 0.03 x min(chains, 10): a protocol live on more chains reaches more farmers
//   implied      = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// recomputes each row from the same figures so the page and board.json agree.
//
// Rewritten 2026-11-16 through the session's own file tools (same model, same arithmetic) so the
// transcript check can see the model being written.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

